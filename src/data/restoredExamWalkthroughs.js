export function buildRestoredWalkthrough(question) {
  const spec = restoredExamWalkthroughs[question.id.replace(/^past-/, '')];
  if (!spec) return undefined;
  let code = spec.code ?? question.blocks.filter(block => block.type === 'code').map(block => block.text).join('\n');
  code = (spec.prefix ?? '') + code;
  for (const [from, to] of spec.edits ?? []) {
    if (!code.includes(from)) throw new Error(`${question.id}: 학습 코드 보정 위치 누락: ${from}`);
    code = code.replaceAll(from, to);
  }
  const walk = buildCodeWalkthrough({
    id: question.id, code, language: spec.language,
    trace: spec.trace.map(([, text]) => text), anchors: spec.trace.map(([anchor]) => anchor),
  });
  const tables = spec.tables?.map(table => ({ type: 'table', ...table })) ?? [];
  if (spec.resultRows) tables.push({ type: 'table', caption: '최종 SQL 결과 표', rows: [spec.resultColumns, ...spec.resultRows] });
  return { ...walk, code, tables, language: spec.language, pitfall: spec.pitfall,
    note: spec.note, kind: spec.kind ?? 'output', input: spec.input ?? '', expectedOutput: spec.expectedOutput };
}
